"""tasks.py — 定義單一交付型任務。

hierarchical 的關鍵：任務寫成「要交付的成果」，且「不預先指派 agent」，
讓 manager 於執行時自行決定拆給誰、什麼順序、要不要退回重做。
若把任務切成多個各自綁定 agent 的步驟，就會退化成 sequential。

{today} 與 {user_request} 於 crew.kickoff(inputs=...) 時填入。
"""

from crewai import Task
from crewai.tasks.llm_guardrail import LLMGuardrail


def build_task(llm) -> Task:
    return Task(
        description=(
            "今天的日期是 {today}。這是當下的真實日期，並非未來日期；"
            "天氣、匯率等工具都查得到此日期（含其後行程期間）的即時資料，"
            "請直接以 {today} 為基準查詢，不要改用更早的日期。\n"
            "使用者的旅遊需求：{user_request}\n\n"
            "請規劃一份符合使用者過往偏好、且預算可行的大阪行程。需涵蓋：\n"
            "1. 從過往台灣旅遊紀錄推斷使用者偏好（住宿風格、景點類型、飲食、步調、預算）。\n"
            "2. 依偏好搜尋大阪最新景點、住宿與交通，並查詢行程期間天氣。\n"
            "3. 換算日圓對新台幣匯率，估算總預算與每人分攤金額。\n"
            "4. 產出三段式偏好說明（原文依據／推理結果／行程影響）、逐日行程、住宿推薦、"
            "交通建議、預算估算與注意事項。\n\n"
            "預算必須算術正確、費用前後一致，住宿價位須貼合偏好等級；"
            "景點營業狀態與票價須經查證。"
        ),
        expected_output=(
            "一份完整的繁體中文行程，包含：三段式偏好說明、逐日行程（依時段安排並標註天氣）、"
            "住宿推薦、交通建議、以日圓與新台幣標示且算術正確的預算估算，以及簽證與注意事項。"
        ),
        # 硬審核：產出先過此關卡，不合格自動退回重做（與 manager 的軟審核互補）。
        # task 未綁 agent（hierarchical 動態委派），故手動建 LLMGuardrail 指定 LLM。
        guardrail=LLMGuardrail(
            description=(
                "以繁體中文檢查這份行程是否全部符合：\n"
                "1) 逐日行程的日期與使用者要求的出發日一致（相對日期如「下週二」須正確換算）。\n"
                "2) 預算逐項加總算術正確，日圓與新台幣換算前後使用同一匯率。\n"
                "3) 住宿與景點票價為具體真實資訊，非「待確認」以外的空泛描述。\n"
                "4) 天氣為行程期間的預報資料，而非過去年份的歷史平均。\n"
                "任一項不符即不通過，並具體說明哪一項、錯在哪。"
            ),
            llm=llm,
        ),
        guardrail_max_retries=2,
        output_file="output/行程結果.md",  # 每輪規劃結果落地成檔，方便閱讀
        # 刻意不指定 agent：交由 manager 於執行時動態委派
    )
